const makeCell = (text, opts = {}) => new TableCell({
  width: { size: opts.w || 2000, type: WidthType.DXA },
  shading: opts.shade ? { type: ShadingType.CLEAR, fill: "E8E0F0" } : undefined,
  children: [new Paragraph({ spacing: { after: 0 }, children: [new TextRun({ text, bold: !!opts.bold, size: 20 })] })]
});

const makeRow = (cells, shade = false) => new TableRow({
  children: cells.map((c, i) => makeCell(c, { shade: shade || i === 0, bold: shade || i === 0, w: Math.floor(PAGE_W / cells.length) }))
});

const makeTable = (headers, rows) => new Table({
  width: { size: PAGE_W, type: WidthType.DXA },
  columnWidths: headers.map(() => Math.floor(PAGE_W / headers.length)),
  rows: [makeRow(headers, true), ...rows.map(r => makeRow(r))]
});

