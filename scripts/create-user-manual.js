const h = (text, level = HeadingLevel.HEADING_1) =>
  new Paragraph({ heading: level, spacing: { before: 300, after: 120 }, children: [new TextRun({ text, bold: true })] });

const p = (text, opts = {}) =>
  new Paragraph({ spacing: { after: 80 }, ...opts, children: [new TextRun({ text, ...opts.run })] });

const pb = (...parts) =>
  new Paragraph({ spacing: { after: 80 }, children: parts.map(part =>
    typeof part === "string" ? new TextRun(part) : new TextRun(part)) });

const pbi = (text) => pb({ text, italics: true });

const bold = (text) => ({ text, bold: true });

const bullet = (text, level = 0) => new Paragraph({
  numbering: { reference: "bullets", level },
  spacing: { after: 40 },
  children: [new TextRun(text)]
});

const bulletBold = (label, desc, level = 0) => new Paragraph({
  numbering: { reference: "bullets", level },
  spacing: { after: 40 },
  children: [new TextRun({ text: label, bold: true }), new TextRun(desc)]
});

